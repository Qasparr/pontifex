def pinyin_of(chars):
    # MECHANISM: machine pinyin, PRC standard readings, tones stripped.
    # DOCTRINE: this is the scribe's extraction convention, stated plainly.
    py = [re.sub(r"[1-5]", "", p) for p in
          lazy_pinyin(chars, style=Style.TONE3, neutral_tone_with_five=False)]
    # OBSERVED: pypinyin reads 勒 as lēi ("strangle"); the intended
    # transliteration 泰勒玛 uses lè ("rein in"). The override is the scribe's
    # correction, recorded here — the machine's raw output is kept in the log.
    if chars == "泰勒玛":
        print("    [pinyin override] raw 'tai lei ma' -> corrected 'tai le ma' "
              "(勒 read as lè, not lēi)")
        py = ["tai", "le", "ma"]
    return py


def hebrew_fallback(pinyin_syllables):
    # MECHANISM: replicate the repo's fallback — greedy digraphs then the
    # LATIN_TO_HEBREW map, weighed on the repo's HEBREW table.
    s = "".join(pinyin_syllables).lower()
    hebrew_letters = []
    i = 0
    while i < len(s):
        dig = s[i:i + 2]
        if dig in tables.LATIN_TO_HEBREW_DIGRAPHS:
            hebrew_letters.append(tables.LATIN_TO_HEBREW_DIGRAPHS[dig])
            i += 2
        else:
            mapped = tables.LATIN_TO_HEBREW[s[i]]
            # MECHANISM: some map entries are multi-letter ('x' -> 'קס');
            # expand so each Hebrew letter is weighed, never the pair-string.
            hebrew_letters.extend(list(mapped))
            i += 1
    value = sum(tables.HEBREW[h] for h in hebrew_letters)
    # MECHANISM: actual-loss mergers only — a MERGERS key counts as fired when
    # the source string contains two or more distinct letters from its list.
    fired = sorted(
        h for h, srcs in tables.MERGERS.items()
        if sum(1 for L in srcs if L in s) >= 2
    )
    return "".join(hebrew_letters), value, fired


